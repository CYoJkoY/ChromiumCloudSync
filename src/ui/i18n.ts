  let current = "en";
  function normalize(v) {
    return /^zh/i.test((v || "").replace("_", "-")) ? "zh-CN" : "en";
  }
  function detectBrowserLanguage() {
    const candidates = [];
    try {
      const uiLang = chrome.i18n?.getUILanguage?.();
      if (uiLang) candidates.push(uiLang);
    } catch {}
    if (navigator.language) candidates.push(navigator.language);
    if (Array.isArray(navigator.languages))
      candidates.push(...navigator.languages);
    return candidates.some((v) => /^zh(?:[-_]|$)/i.test(String(v)))
      ? "zh-CN"
      : "en";
  }
  async function initI18n() {
    const s = await chrome.storage.local.get("language");
    current =
      s.language && s.language !== "auto"
        ? normalize(s.language)
        : detectBrowserLanguage();
    return current;
  }
  async function setLanguage(v) {
    await chrome.storage.local.set({ language: v });
    current = v === "auto" ? detectBrowserLanguage() : normalize(v);
    applyI18n();
    return current;
  }
  function t(key, vars = {}) {
    let s = DICT[current]?.[key] ?? DICT.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
  }
  function setTranslatedText(element, text) {
    if (!element) return;
    if (element.children.length === 0) {
      element.textContent = text;
      return;
    }
    const textNode = [...element.childNodes].find(
      (node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim(),
    );
    if (textNode) {
      textNode.textContent = text;
    } else {
      const marker = document.createTextNode(text);
      element.insertBefore(marker, element.firstChild);
    }
  }
  function applyI18n(root = document) {
    root.documentElement.lang = current;
    root
      .querySelectorAll("[data-i18n]")
      .forEach((e) => setTranslatedText(e, t(e.dataset.i18n)));
    root
      .querySelectorAll("[data-i18n-placeholder]")
      .forEach((e) =>
        e.setAttribute("placeholder", t(e.dataset.i18nPlaceholder)),
      );
  }
  async function initAndApply(root = document) {
    await initI18n();
    applyI18n(root);
  }
  window.CCSyncI18n = {
    initI18n,
    setLanguage,
    t,
    applyI18n,
    initAndApply,
    currentLanguage: () => current,
  };
